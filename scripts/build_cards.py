def build(project: Project, theme: str, *, mobile: bool = False) -> str:
    p = PALETTES[theme]
    width, height = (640, 250) if mobile else (1200, 192)
    title_id = f"{project.slug}-title"
    description_id = f"{project.slug}-description"
    content = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" '
        f'aria-labelledby="{title_id} {description_id}">',
        f'<title id="{title_id}">{escape(project.title)} — {escape(project.category.title())}</title>',
        f'<desc id="{description_id}">{escape(project.description)} '
        f'{escape(project.stack)}.</desc>',
        f'<rect x="0.5" y="0.5" width="{width - 1}" height="{height - 1}" rx="12" '
        f'fill="{p.background}" stroke="{p.stroke}"/>',
    ]
    if mobile:
        content.extend(
            (
                label(project.number, 28, 38, 14, p.muted, mono=True, tracking="0.5"),
                f'<path d="M62 27v14" stroke="{p.stroke}"/>',
                label(project.category, 79, 38, 14, p.accent, mono=True, tracking="1.7"),
                arrow(594, 25, p),
                label(
                    project.title,
                    28,
                    86,
                    30,
                    p.foreground,
                    weight=600,
                    tracking="-0.6",
                ),
                label(project.mobile_lines[0], 28, 125, 22, p.muted),
                label(project.mobile_lines[1], 28, 155, 22, p.muted),
                f'<path d="M28 185h584" stroke="{p.stroke}"/>',
                f'<rect x="28" y="210" width="5" height="5" rx="1" fill="{p.accent}"/>',
                label(project.stack, 46, 218, 13, p.muted, mono=True, tracking="0.7"),
            )
        )
    else:
        content.extend(
            (
                label(project.number, 32, 37, 13, p.muted, mono=True, tracking="0.5"),
                f'<path d="M76 27v138" stroke="{p.stroke}"/>',
                f'<rect x="32" y="62" width="13" height="2" rx="1" fill="{p.accent}"/>',
                label(project.category, 110, 37, 13, p.accent, mono=True, tracking="2"),
                label(project.title, 110, 77, 34, p.foreground, weight=600, tracking="-0.8"),
                label(project.description, 110, 115, 20, p.muted),
                label(project.stack, 110, 152, 12, p.muted, mono=True, tracking="1.1"),
                symbol(project, p),
                arrow(1144, 27, p),
            )
        )
    content.append("</svg>")
    return "\n".join(content) + "\n"


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for project in PROJECTS:
        for theme in PALETTES:
            for mobile in (False, True):
                variant = "-mobile" if mobile else ""
                path = OUTPUT / f"{project.slug}{variant}-{theme}.svg"
                path.write_text(build(project, theme, mobile=mobile), encoding="utf-8")
                print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
