def label(
    content: str,
    x: int,
    y: int,
    size: int,
    color: str,
    *,
    mono: bool = False,
    weight: int = 400,
    tracking: str = "0",
    extra: str = "",
) -> str:
    font = MONO if mono else SANS
    return (
        f'<text x="{x}" y="{y}" fill="{color}" font-family="{font}" '
        f'font-size="{size}" font-weight="{weight}" letter-spacing="{tracking}"'
        f'{extra}>{escape(content)}</text>'
    )


def arrow(x: int, y: int, palette: Palette) -> str:
    return (
        f'<g transform="translate({x} {y})" fill="none" stroke="{palette.muted}" '
        'stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" '
        'aria-hidden="true">'
        '<path d="M0 14 14 0M0 0h14v14"/>'
        '</g>'
    )


