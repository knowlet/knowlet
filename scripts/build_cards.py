#!/usr/bin/env python3
"""Build original, self-contained project cards for the knowlet profile.

Run from any directory: python3 scripts/build_cards.py
Only the Python standard library is required. No downloaded assets or fonts.
"""

from dataclasses import dataclass
from html import escape
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "assets" / "projects"
SANS = "Arial, Helvetica, sans-serif"
MONO = "ui-monospace, SFMono-Regular, Consolas, monospace"


@dataclass(frozen=True)
class Palette:
    background: str
    stroke: str
    foreground: str
    muted: str
    accent: str
    teal: str


PALETTES = {
    "dark": Palette("#0b1418", "#24373c", "#edf5ee", "#9ab1b5", "#cbf278", "#66d7ca"),
    "light": Palette("#f3f6f2", "#d1ddd7", "#122d2a", "#536864", "#497323", "#007e78"),
}


@dataclass(frozen=True)
class Project:
    slug: str
    number: str
    title: str
    category: str
    description: str
    stack: str
    mobile_lines: tuple[str, str]


